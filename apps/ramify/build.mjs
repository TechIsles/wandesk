// This app's build: src/ui → public/ and src/server → server.js. After editing src/, run in this directory:
//   npm install && npm run build
// The host is not involved in compiling and carries no dependency on it.
import esbuild from "esbuild";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(here, "app.json"), "utf8"));
const pub = path.join(here, "public");
fs.mkdirSync(pub, { recursive: true });

// Frontend
await esbuild.build({
  entryPoints: [path.join(here, "src/ui/main.tsx")],
  bundle: true,
  format: "esm",
  target: ["es2022"],
  jsx: "automatic",
  minify: true,
  legalComments: "none",
  loader: { ".png": "dataurl", ".jpg": "dataurl", ".svg": "dataurl" },
  outfile: path.join(pub, "app.js"),
  logLevel: "warning",
});

fs.writeFileSync(path.join(pub, "index.html"), `<!doctype html>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="color-scheme" content="light dark" />
<title>${manifest.name || manifest.id}</title>
<link rel="stylesheet" href="/app.css" />
<script src="/_wd/sdk.js"></script>
<div id="root"></div>
<script type="module" src="/app.js"></script>
`);

// Backend: one Worker module with marked inlined
await esbuild.build({
  entryPoints: [path.join(here, "src/server/index.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: ["es2022"],
  minify: false,
  legalComments: "none",
  outfile: path.join(here, "server.js"),
  banner: { js: "// Built from src/server/index.ts by build.mjs — edit the source and rebuild; do not edit this file by hand." },
  logLevel: "warning",
});

const size = fs.readdirSync(pub).reduce((n, f) => n + fs.statSync(path.join(pub, f)).size, 0);
console.log(`${manifest.id}: public/ ${Math.round(size / 1024)} KB, server.js ${Math.round(fs.statSync(path.join(here, "server.js")).size / 1024)} KB`);
